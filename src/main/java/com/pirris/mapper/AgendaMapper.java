package com.pirris.mapper;

import java.util.List;
import java.util.UUID;

import org.mapstruct.Mapper;
import org.mapstruct.Mapping;
import org.mapstruct.MappingConstants;

import com.pirris.dto.agenda.CalendarSlotDto;
import com.pirris.dto.agenda.SessionDetailDto;
import com.pirris.dto.agenda.SessionParticipantDto;
import com.pirris.dto.agenda.UnavailabilityDto;
import com.pirris.model.SessionParticipantModel;
import com.pirris.model.TrainingSessionModel;
import com.pirris.model.UnavailabilityModel;

/**
 * Compile-time mapper from sessions, participants and unavailability blocks to
 * the Agenda view DTOs. Generated by MapStruct as a CDI bean. Sessions and
 * unavailability remain separate entities; they meet only in
 * {@link CalendarSlotDto}.
 */
@Mapper(componentModel = MappingConstants.ComponentModel.CDI)
public interface AgendaMapper {

    // ---- entity -> DTO (reads) ----

    SessionParticipantDto toParticipantDto(SessionParticipantModel participant);

    List<SessionParticipantDto> toParticipantDtos(List<SessionParticipantModel> participants);

    /** A session with its (already mapped) participants. */
    @Mapping(target = "id", source = "session.id")
    @Mapping(target = "startDate", source = "session.startDate")
    @Mapping(target = "durationMinutes", source = "session.durationMinutes")
    @Mapping(target = "serviceId", source = "session.serviceId")
    @Mapping(target = "courseId", source = "session.courseId")
    @Mapping(target = "notes", source = "session.notes")
    @Mapping(target = "status", source = "session.status")
    @Mapping(target = "invoiceDate", source = "session.invoiceDate")
    @Mapping(target = "participants", source = "participants")
    SessionDetailDto toSessionDetail(TrainingSessionModel session, List<SessionParticipantDto> participants);

    UnavailabilityDto toUnavailabilityDto(UnavailabilityModel unavailability);

    /** Calendar block of a session; {@code end} = start + duration. */
    @Mapping(target = "type", constant = "SESSION")
    @Mapping(target = "id", source = "session.id")
    @Mapping(target = "start", source = "session.startDate")
    @Mapping(target = "end", expression = "java(session.startDate.plusMinutes(session.durationMinutes))")
    @Mapping(target = "allDay", constant = "false")
    @Mapping(target = "status", source = "session.status")
    @Mapping(target = "serviceId", source = "session.serviceId")
    @Mapping(target = "courseId", source = "session.courseId")
    @Mapping(target = "clientIds", source = "clientIds")
    @Mapping(target = "reason", ignore = true)
    @Mapping(target = "notes", source = "session.notes")
    CalendarSlotDto sessionSlot(TrainingSessionModel session, List<UUID> clientIds);

    /** Calendar block of an unavailability; no session fields, no clients. */
    @Mapping(target = "type", constant = "UNAVAILABILITY")
    @Mapping(target = "start", source = "startDate")
    @Mapping(target = "end", source = "endDate")
    @Mapping(target = "status", ignore = true)
    @Mapping(target = "serviceId", ignore = true)
    @Mapping(target = "courseId", ignore = true)
    @Mapping(target = "clientIds", expression = "java(java.util.List.of())")
    CalendarSlotDto unavailabilitySlot(UnavailabilityModel unavailability);
}
